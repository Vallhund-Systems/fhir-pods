#!/usr/bin/env python3
"""Emit `src/rules_invariants.rs`: every invariant key the core can report
(the base tables in `typemap.rs`, every compiled profile's invariants, and
the keys the shape walk reports itself), each paired with its stable id
`inv.<key>` — so a rule id is a `&'static str` without allocation.

    python3 tools/gen_rules.py crates/fhir-pods-core/src
"""
import os
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "crates", "fhir-pods-core", "src")
keys = set()
# the base tables: every key as the core reports it — the quoted token
# shaped like a key (`cmp-1`, `sdf-8a`, `bdl-10`) within the invariant tables
typemap = open(os.path.join(src, "typemap.rs")).read()
tables = typemap[typemap.index("pub static DOMAIN_INVARIANTS"):typemap.index("pub static BASE_BINDINGS")]
keys |= set(re.findall(r'"([a-z][a-z0-9]*(?:-[a-z0-9]+)*-\d+[a-z]?)"', tables))
# every compiled profile's keys, verbatim (`pvc2`, `hasMemberOrComponent` included)
gen = os.path.join(src, "generated")
for name in os.listdir(gen):
    if name.endswith(".rs"):
        keys |= set(re.findall(r'key: "([^"]+)"', open(os.path.join(gen, name)).read()))
# the walk's own
keys |= {"ele-1", "ext-1", "dom-2", "dom-3", "dom-4", "dom-5", "dom-6", "ref-1", "txt-1", "txt-2", "bdl-1", "bdl-2",
         "bdl-3", "bdl-4", "bdl-7", "bdl-9", "bdl-10", "bdl-11", "bdl-12"}
# verbatim: a key is whatever the definitions call it, never a space or a quote
keys = sorted(k for k in keys if k and " " not in k and '"' not in k)
out = os.path.join(src, "rules_invariants.rs")
with open(out, "w") as f:
    f.write("// GENERATED by tools/gen_rules.py — do not edit.\n")
    f.write("/// Every invariant key the core can report, with its rule id, sorted.\n")
    f.write("pub static INVARIANT_IDS: &[(&str, &str)] = &[\n")
    for k in keys:
        f.write(f'    ("{k}", "inv.{k}"),\n')
    f.write("];\n")
print(f"wrote {out}: {len(keys)} invariant keys")
