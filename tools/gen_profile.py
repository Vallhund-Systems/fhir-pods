#!/usr/bin/env python3
"""Generate a Rust `CompiledProfile` from a FHIR StructureDefinition snapshot.

The codegen step of fhir-pods: read the pre-computed `snapshot.element` the
published FHIR/AU-Core packages already ship, and emit a compiled, embeddable
profile (our own IR — no FHIRSchema dependency). See docs/domain-model.md.

Emits one `ElementConstraint` per non-sliced element that carries an enforceable
constraint: cardinality (min / bounded max), a fixed scalar value, or a
required-strength binding on a code. Nested paths are emitted — the engine
evaluates cardinality per parent instance.

Deferred (counted, not emitted): anything inside a slice (`sliceName`, or an
`id` containing ':'), pattern[x], and mustSupport-only elements — pending the
slicing pass. Slice-scoped elements MUST be excluded here: two slices of the
same path carry different fixed values, and flattening them would demand both.

Licence rule: a fixed value is emitted only for scalar fixed[x] (uri/code/
string…). Fixed Codings are handled per-field (system/code) — display is never
emitted (the code is a reference; the display is licensed content).

Usage:
    gen_profile.py <StructureDefinition.json> <out.rs> "<package id version>"
"""
import json
import os
import sys

SCALAR = (str, int, float, bool)


def build(sd):
    resource_type = sd["type"]
    elements = (sd.get("snapshot") or {}).get("element", [])
    rules = {}          # path -> dict(min, max, fixed, binding)
    deferred = 0
    for e in elements:
        path = e.get("path", "")
        if "." not in path:                     # the root element
            continue
        sliced = "sliceName" in e or ":" in e.get("id", "")
        min_ = e.get("min", 0) or 0
        max_ = e.get("max")                     # "1" / "*" / None
        binding = e.get("binding") or {}
        strength = binding.get("strength")
        vs = binding.get("valueSet")
        types = [t.get("code") for t in e.get("type", [])]
        fixed_key = next((k for k in e if k.startswith("fixed")), None)
        fixed = e.get(fixed_key) if fixed_key else None
        pattern = any(k.startswith("pattern") for k in e)
        scalar_fixed = isinstance(fixed, SCALAR) and not isinstance(fixed, bool)
        bounded_max = max_ is not None and max_ != "*"
        enforce_binding = strength == "required" and "code" in types and bool(vs)
        enforceable = min_ >= 1 or bounded_max or scalar_fixed or enforce_binding
        if sliced or pattern or (fixed is not None and not scalar_fixed):
            deferred += 1
            continue
        if not enforceable:
            if e.get("mustSupport") or strength in ("required", "extensible"):
                deferred += 1
            continue
        r = rules.setdefault(path, {"min": 0, "max": None, "fixed": None, "binding": None})
        r["min"] = max(r["min"], min_)
        if bounded_max:
            r["max"] = int(max_) if r["max"] is None else min(r["max"], int(max_))
        if scalar_fixed:
            r["fixed"] = str(fixed)
        if enforce_binding:
            r["binding"] = vs
    return resource_type, rules, deferred


def rs_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit(sd, provenance):
    resource_type, rules, deferred = build(sd)
    name = sd.get("title") or sd.get("name") or sd.get("id")
    out = [
        f"//! @generated by tools/gen_profile.py from {provenance} — do not edit by hand.",
        f"//! Profile: {name}  <{sd.get('url')}>",
        f"//! Coverage: {len(rules)} element constraint(s) enforced; {deferred} deferred",
        "//! (slices / pattern[x] / mustSupport-only — pending the slicing pass).",
        "",
        "use crate::compiled::{CompiledProfile, ElementConstraint, Max};",
        "",
        "pub static PROFILE: CompiledProfile = CompiledProfile {",
        f"    url: {rs_str(sd.get('url'))},",
        f"    name: {rs_str(name)},",
        f"    resource_type: {rs_str(resource_type)},",
        f"    deferred: {deferred},",
        "    elements: &[",
    ]
    for path in sorted(rules):
        r = rules[path]
        mx = f"Max::Bounded({r['max']})" if r["max"] is not None else "Max::Star"
        fx = f"Some({rs_str(r['fixed'])})" if r["fixed"] is not None else "None"
        bd = f"Some({rs_str(r['binding'])})" if r["binding"] else "None"
        out.append(
            f"        ElementConstraint {{ path: {rs_str(path)}, min: {r['min']}, max: {mx}, "
            f"fixed: {fx}, required_binding: {bd} }},"
        )
    out += ["    ],", "};", ""]
    return "\n".join(out)


def main():
    sd_path, out_path, provenance = sys.argv[1], sys.argv[2], sys.argv[3]
    sd = json.load(open(sd_path))
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(emit(sd, provenance))
    _, rules, deferred = build(sd)
    print(f"wrote {out_path}: {len(rules)} enforced, {deferred} deferred")


if __name__ == "__main__":
    main()
