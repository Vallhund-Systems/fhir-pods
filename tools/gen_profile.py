#!/usr/bin/env python3
"""Generate a Rust `CompiledProfile` from a FHIR StructureDefinition snapshot.

This is the codegen step of fhir-pods: read the pre-computed `snapshot.element`
that the published FHIR/AU-Core packages already ship, and emit a compiled,
embeddable profile table (our own IR — no FHIRSchema dependency).

This first cut emits the constraints the engine enforces today — **top-level**
mandatory elements (min>=1) and **required bindings on top-level code elements**.
Deeper rules (nested paths, slicing/discriminators, fixed[x]/pattern[x],
mustSupport) are counted as `deferred` until the nested engine lands, so the
generated profile is honest about its own coverage.

Usage:
    gen_profile.py <StructureDefinition.json> <out.rs> "<package id version>"
"""
import json
import os
import sys


def build(sd):
    resource_type = sd["type"]
    elements = (sd.get("snapshot") or {}).get("element", [])
    rules = {}          # top-level path -> {"min": int, "binding": url|None}
    deferred = 0
    for e in elements:
        path = e.get("path", "")
        if "." not in path:            # the root element
            continue
        depth = path.count(".")
        min_ = e.get("min", 0) or 0
        binding = e.get("binding") or {}
        strength = binding.get("strength")
        vs = binding.get("valueSet")
        types = [t.get("code") for t in e.get("type", [])]
        is_slice = "sliceName" in e
        top = depth == 1 and not is_slice
        enforce_min = min_ >= 1
        enforce_binding = strength == "required" and "code" in types and vs
        if top and (enforce_min or enforce_binding):
            r = rules.setdefault(path, {"min": 0, "binding": None})
            r["min"] = max(r["min"], min_)
            if enforce_binding:
                r["binding"] = vs
        elif enforce_min or strength in ("required", "extensible") or is_slice or e.get("mustSupport"):
            deferred += 1
    return resource_type, rules, deferred


def emit(sd, provenance):
    resource_type, rules, deferred = build(sd)
    name = sd.get("title") or sd.get("name") or sd.get("id")
    enforced = len(rules)
    out = []
    out.append(f"//! @generated by tools/gen_profile.py from {provenance} — do not edit by hand.")
    out.append(f"//! Profile: {name}  <{sd.get('url')}>")
    out.append(f"//! Coverage: {enforced} top-level rule(s) enforced; {deferred} deferred")
    out.append("//! (nested paths / slicing / fixed[x] / mustSupport — pending the nested engine).")
    out.append("")
    out.append("use crate::compiled::{CompiledProfile, ElementRule};")
    out.append("")
    out.append("pub static PROFILE: CompiledProfile = CompiledProfile {")
    out.append(f'    url: "{sd.get("url")}",')
    out.append(f'    name: "{name}",')
    out.append(f'    resource_type: "{resource_type}",')
    out.append(f"    deferred: {deferred},")
    out.append("    rules: &[")
    for path in sorted(rules):
        r = rules[path]
        b = f'Some("{r["binding"]}")' if r["binding"] else "None"
        out.append(f'        ElementRule {{ path: "{path}", min: {r["min"]}, required_binding: {b} }},')
    out.append("    ],")
    out.append("};")
    out.append("")
    return "\n".join(out)


def main():
    sd_path, out_path, provenance = sys.argv[1], sys.argv[2], sys.argv[3]
    sd = json.load(open(sd_path))
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(emit(sd, provenance))
    rt, rules, deferred = build(sd)
    print(f"wrote {out_path}: {len(rules)} enforced, {deferred} deferred")


if __name__ == "__main__":
    main()
