#!/usr/bin/env python3
"""Generate the known-definition table (`src/known_urls.rs`): every canonical
URL (and NamingSystem uniqueId) the compiled packages define, under the
"known spaces" — `http://hl7.org/fhir`, `http://terminology.hl7.org/`,
`http://fhir.org/guides`.

The reference validator holds a `uri` / `url` value in those spaces to a
higher standard than any other: one it cannot resolve to a definition is an
error ("No definition could be found for URL value"), where an unknown URL
anywhere else is taken on trust. The spaces are HL7's own, so a value there
that names nothing is a typo (`http://hl7.org/fhir/sid/us-ssn.`), not an
unregistered local system. The table is the same packages the profiles are
compiled from, stored as sorted 32-bit FNV-1a hashes (a colliding typo would
pass unremarked — one chance in ~500,000 per unknown value; the table would
be fourteen times larger as strings).

Usage:
    gen_known_urls.py <out.rs> <package/dir>...
"""
import glob
import json
import os
import sys

SPACES = ("http://hl7.org/fhir", "http://terminology.hl7.org/", "http://fhir.org/guides")

# What the reference validator knows without a package: the FHIRPath system
# types a primitive's `type.code` names (`isDefinitionURL`), and the mapping
# spaces a `uri` may name (`isMappingUri`, the ones under the known spaces).
BUILT_IN = (
    "http://hl7.org/fhirpath/System.Boolean", "http://hl7.org/fhirpath/System.String",
    "http://hl7.org/fhirpath/System.Integer", "http://hl7.org/fhirpath/System.Decimal",
    "http://hl7.org/fhirpath/System.Date", "http://hl7.org/fhirpath/System.Time",
    "http://hl7.org/fhirpath/System.DateTime", "http://hl7.org/fhirpath/System.Quantity",
    "http://hl7.org/fhir/fivews", "http://hl7.org/fhir/workflow", "http://hl7.org/fhir/interface",
    "http://hl7.org/fhir/w5", "http://hl7.org/fhir/logical", "http://hl7.org/fhir/auditevent",
    "http://hl7.org/fhir/provenance", "http://hl7.org/fhir/object-implementation", "http://hl7.org/fhir/rr",
    "http://hl7.org/fhir/composition", "http://hl7.org/fhir/documentreference",
)


def fnv1a32(s):
    h = 0x811C9DC5
    for b in s.encode("utf-8"):
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    out_path, dirs = sys.argv[1], sys.argv[2:]
    urls = set()
    for d in dirs:
        index = os.path.join(d, ".index.json")
        if os.path.exists(index):
            for f in json.load(open(index)).get("files", []):
                if f.get("url"):
                    urls.add(f["url"].split("|")[0])
        for p in glob.glob(os.path.join(d, "NamingSystem-*.json")):
            for u in json.load(open(p)).get("uniqueId", []):
                if u.get("type") == "uri" and u.get("value"):
                    urls.add(u["value"])
    urls |= set(BUILT_IN)
    known = sorted({fnv1a32(u) for u in urls if u.startswith(SPACES)})
    with open(out_path, "w") as f:
        f.write("//! Generated by tools/gen_known_urls.py — do not edit.\n")
        f.write("//!\n")
        f.write("//! The definitions the compiled packages hold under HL7's own URL spaces\n")
        f.write("//! (`http://hl7.org/fhir`, `http://terminology.hl7.org/`, `http://fhir.org/guides`):\n")
        f.write("//! every canonical and NamingSystem uniqueId, as sorted 32-bit FNV-1a hashes.\n")
        f.write("//! A `uri` / `url` value in those spaces that is none of them is an error, as\n")
        f.write("//! the reference validator has it; a value anywhere else is taken on trust.\n\n")
        f.write(f"/// {len(known)} definitions.\n")
        f.write("pub static KNOWN_SPACE_URLS: &[u32] = &[\n")
        for i in range(0, len(known), 8):
            f.write("    " + ", ".join(f"0x{h:08x}" for h in known[i : i + 8]) + ",\n")
        f.write("];\n\n")
        f.write("/// Is `url` in one of HL7's own spaces — where an unknown value is a typo, not a local system?\n")
        f.write("pub fn in_known_space(url: &str) -> bool {\n")
        f.write("    " + " || ".join(f"url.starts_with({json.dumps(s)})" for s in SPACES) + "\n")
        f.write("}\n\n")
        f.write("/// Is `url` (a version suffix `|x` or a fragment `#x` dropped) a definition the packages hold?\n")
        f.write("pub fn known_definition(url: &str) -> bool {\n")
        f.write("    let url = url.split(['|', '#']).next().unwrap_or(url);\n")
        f.write("    let mut h: u32 = 0x811c9dc5;\n")
        f.write("    for b in url.bytes() {\n")
        f.write("        h = (h ^ u32::from(b)).wrapping_mul(0x01000193);\n")
        f.write("    }\n")
        f.write("    KNOWN_SPACE_URLS.binary_search(&h).is_ok()\n")
        f.write("}\n")
    print(f"wrote {out_path}: {len(known)} known-space definitions from {len(urls)} canonicals")


if __name__ == "__main__":
    main()
