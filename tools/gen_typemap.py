#!/usr/bin/env python3
"""Generate the element-type table (`src/typemap.rs`) from the base FHIR
package: for every element of the resource types the registry compiles (plus
the Resource / DomainResource bases) and of every complex datatype, its FHIR
type. This is what lets a JSON node know its type — `descendants().as(canonical)`,
`value.ofType(Quantity)`, `$this is dateTime` on arbitrary nodes — without the
document carrying any type information itself.

Kept small on purpose: `id` / `extension` / `modifierExtension` are implicit
(the lookup knows them), and only registry resource types are included; a
node under a resource type we have no profile for simply has no type and
type-dependent FHIRPath is skipped, never guessed.

Usage:
    gen_typemap.py <r4.core/package/dir> <generated/profiles/dir> <out.rs>
"""
import glob
import json
import os
import re
import sys

IMPLICIT = {"id", "extension", "modifierExtension"}


def main():
    pkg, generated, out_path = sys.argv[1], sys.argv[2], sys.argv[3]

    wanted = {"Resource", "DomainResource"}
    for f in glob.glob(os.path.join(generated, "*.rs")):
        m = re.search(r'\n    resource_type: "([^"]+)"', open(f).read())
        if m:
            wanted.add(m.group(1))

    sds = {}
    for p in glob.glob(os.path.join(pkg, "StructureDefinition-*.json")):
        d = json.load(open(p))
        if d.get("derivation") == "specialization" and d.get("kind") in ("resource", "complex-type"):
            sds[d["type"]] = d

    types = sorted(t for t in sds if sds[t]["kind"] == "complex-type" or t in wanted)
    entries = []
    for t in types:
        for e in sds[t]["snapshot"]["element"]:
            path = e["path"]
            if "." not in path or path.rsplit(".", 1)[1] in IMPLICIT:
                continue
            if e.get("contentReference"):
                codes = ["#" + e["contentReference"].split("#")[-1]]
            else:
                codes = [x["code"] for x in e.get("type", []) if x.get("code")]
            codes = [c.rsplit("/", 1)[-1].replace("System.", "") for c in codes]  # fhirpath System.String → String
            if not codes:
                continue
            entries.append((path, "|".join(codes)))
    entries.sort()

    with open(out_path, "w") as f:
        f.write("//! @generated by tools/gen_typemap.py from hl7.fhir.r4.core 4.0.1 — do not edit by hand.\n")
        f.write(f"//! {len(entries)} element types across {len(types)} types (registry resources + all datatypes).\n\n")
        f.write("/// Type names known to the table (resources and datatypes), sorted.\n")
        f.write("pub static TYPES: &[&str] = &[\n")
        for t in types:
            f.write(f'    "{t}",\n')
        f.write("];\n\n")
        f.write("/// (`Type.element.path`, `type|type…` or `#contentReference.path`), sorted by path.\n")
        f.write("pub static TABLE: &[(&str, &str)] = &[\n")
        for path, ty in entries:
            f.write(f'    ("{path}", "{ty}"),\n')
        f.write("];\n")
    print(f"wrote {out_path}: {len(entries)} entries, {len(types)} types")


if __name__ == "__main__":
    main()
