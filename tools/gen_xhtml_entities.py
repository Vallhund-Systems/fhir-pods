#!/usr/bin/env python3
"""The named character references the reference validator knows from
HTML and refuses in a narrative ("Invalid entity in the XHTML"): the
HTML5 list (as Python ships it) less XML's own five, which decode, and
the four legacy uppercase names (AMP, GT, LT, QUOT) it does not know —
probed name by name against validator_cli 6.10.4 (2,116 names).
Writes crates/fhir-pods-core/src/xhtml_entities.rs."""
import html.entities, pathlib
names = {k.rstrip(";") for k in html.entities.html5} | set(html.entities.name2codepoint)
names -= {"amp", "apos", "gt", "lt", "quot", "AMP", "GT", "LT", "QUOT"}
out = pathlib.Path(__file__).resolve().parents[1] / "crates/fhir-pods-core/src/xhtml_entities.rs"
body = "[\n" + "".join(f'    "{n}",\n' for n in sorted(names)) + "]\n"
out.write_text("// generated by tools/gen_xhtml_entities.py — do not edit\n" + body)
print(f"{len(names)} names -> {out}")
